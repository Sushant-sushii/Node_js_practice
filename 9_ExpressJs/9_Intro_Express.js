// Express Js is a minimal and flexible web application for Node.js
// It provides a robust set of features for building single-page ,multi-page,and hybrid web applications.
// Express.js simplifies server-side coding by providing a layer of fundamental web application features 
// Features of Express.js:

// 1. Routing: Express.js provides a powerful routing mechanism that allows you to define routes for different HTTP methods and URL patterns.
// 2. Middleware: Express.js uses middleware functions to handle requests and responses. Middleware functions can perform tasks such as logging, authentication, and error handling.
// 3. Templating Engines: Express.js supports various templating engines like EJS, Pug, and Handlebars, allowing you to generate dynamic HTML pages.
// 4. Static Files: Express.js can serve static files such as images, CSS, and JavaScript files using the built-in middleware function express.static().
// 5. RESTful APIs: Express.js makes it easy to create RESTful APIs by providing a simple way to define routes and handle HTTP requests.

